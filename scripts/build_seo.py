def table(rows, name):
    headings = ["#", "Club", "P", "W", "D", "L", "GD", "Pts"]
    cells = "".join(f"<th scope=\"col\">{h}</th>" for h in headings)
    trs = []
    for idx, row in enumerate(rows, 1):
        gd = f"+{row['GD']}" if row["GD"] > 0 else str(row["GD"])
        values = [idx, row["name"], row["P"], row["W"], row["D"], row["L"], gd, row["Pts"]]
        if idx == 1:
            tr_class = ' class="champion"'
        else:
            tr_class = ""
        trs.append("<tr" + tr_class + ">" + "".join(
            f'<th scope="row">{e(v)}</th>' if i == 0 else f'<td>{e(v)}</td>'
            for i, v in enumerate(values)
        ) + "</tr>")
    return f'<div class="table-scroll"><table aria-label="{e(name)}"><thead><tr>{cells}</tr></thead><tbody>{"".join(trs)}</tbody></table></div>'


