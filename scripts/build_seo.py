        f"<strong>{e(winner['name'])}</strong> win our alternative {e(label)} La Liga "
        f"on <strong>{winner['Pts']} points</strong> from {winner['P']} matches. "
        f"{e(runner['name'])} follow on {runner['Pts']} points."
